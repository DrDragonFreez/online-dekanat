def normalize_label(s: str) -> str:
    s = s.lower().replace("ё", "е")
    s = s.replace(".", "").replace("/", " ").replace("-", " ")
    s = re.sub(r"\s+", " ", s)
    return s.strip(" :;")
_LABEL_INDEX = None
def _build_label_index():
    global _LABEL_INDEX
    if _LABEL_INDEX is not None:
        return _LABEL_INDEX
    idx = {}
    for key, synonyms in LABEL_SYNONYMS.items():
        for s in synonyms:
            idx[normalize_label(s)] = key
    _LABEL_INDEX = idx
    return idx
def find_key_by_label(label: str) -> str | None:
    idx = _build_label_index()
    return idx.get(normalize_label(label))
